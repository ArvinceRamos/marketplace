create table app.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references app.profiles (id) on delete cascade,
  target_type app.report_target not null,
  listing_id uuid references app.listings (id) on delete set null,
  reported_user_id uuid references app.profiles (id) on delete set null,
  reason app.report_reason not null,
  details text check (char_length(details) <= 1000),
  status app.report_status not null default 'open',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- The target id may become null later (target deleted); the report is kept.
  -- reports_guard requires the target on insert.
  constraint reports_one_target check (
    (target_type = 'listing' and reported_user_id is null) or
    (target_type = 'user' and listing_id is null)
  ),
  constraint reports_not_self check (reporter_id <> reported_user_id)
);
create unique index reports_open_listing_uq on app.reports (reporter_id, listing_id)
  where status = 'open' and target_type = 'listing';
create unique index reports_open_user_uq on app.reports (reporter_id, reported_user_id)
  where status = 'open' and target_type = 'user';
create index reports_queue_idx on app.reports (status, created_at);
create trigger reports_updated_at before update on app.reports
  for each row execute function app.set_updated_at();

create function app.reports_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if (new.target_type = 'listing' and new.listing_id is null)
     or (new.target_type = 'user' and new.reported_user_id is null) then
    raise exception 'report target is required' using errcode = '23514';
  end if;
  if new.target_type = 'listing' and exists (
    select 1 from app.listings where id = new.listing_id and seller_id = new.reporter_id
  ) then
    raise exception 'cannot report your own listing' using errcode = '23514';
  end if;
  new.status := 'open';
  return new;
end;
$$;
create trigger reports_guard before insert on app.reports
  for each row execute function app.reports_guard();

