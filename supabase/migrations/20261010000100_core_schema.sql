language plpgsql set search_path = '' as $$
begin
  if new.id <> old.id or new.created_at <> old.created_at
     or new.age_confirmed_at is distinct from old.age_confirmed_at then
    raise exception 'profile field is read-only' using errcode = '42501';
  end if;
  return new;
end;
$$;
create trigger profiles_guard before update on app.profiles
  for each row execute function app.profiles_guard();

-- New auth user -> profile. Email sign-ups must confirm they are 18+.
create function app.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  confirmed boolean := coalesce((new.raw_user_meta_data ->> 'age_confirmed')::boolean, false);
  provider text := coalesce(new.raw_app_meta_data ->> 'provider', 'email');
begin
  if provider = 'email' and not confirmed then
    raise exception 'age confirmation required' using errcode = '23514';
  end if;
  insert into app.profiles (id, username, age_confirmed_at)
  values (
    new.id,
    'user_' || substr(replace(new.id::text, '-', ''), 1, 12),
    case when confirmed then now() end
  );
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function app.handle_new_user();

