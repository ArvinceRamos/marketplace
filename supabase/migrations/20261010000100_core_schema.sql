create function app.messages_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  c record;
begin
  select buyer_id, seller_id into c from app.conversations where id = new.conversation_id;
  if c.buyer_id is null or c.seller_id is null then
    raise exception 'the other user has left' using errcode = '23514';
  end if;
  if new.kind = 'text' and app.is_blocked_between(c.buyer_id, c.seller_id) then
    raise exception 'blocked' using errcode = '42501';
  end if;
  new.created_at := now();
  return new;
end;
$$;
create trigger messages_guard before insert on app.messages
  for each row execute function app.messages_guard();

create function app.messages_touch_conversation() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update app.conversations
     set last_message_at = new.created_at,
         buyer_last_read_at = case when new.sender_id = buyer_id
                                   then new.created_at else buyer_last_read_at end,
         seller_last_read_at = case when new.sender_id = seller_id
                                    then new.created_at else seller_last_read_at end
   where id = new.conversation_id;
  return null;
end;
$$;
create trigger messages_touch_conversation after insert on app.messages
  for each row execute function app.messages_touch_conversation();

-- Offer rules: copy parties from the conversation, legal transitions by role,
-- and a chat message for every offer event.
create function app.offers_guard() returns trigger
-- Invoker rights on purpose (see conversations_guard).
language plpgsql set search_path = '' as $$
declare
  c record;
  me uuid := (select auth.uid());
  internal boolean := current_user not in ('anon', 'authenticated');
begin
  if tg_op = 'INSERT' then
    select cv.buyer_id, cv.seller_id, cv.listing_id, l.status as listing_status
      into c
      from app.conversations cv join app.listings l on l.id = cv.listing_id
     where cv.id = new.conversation_id;
    if not found then
      -- Caller cannot see this conversation (RLS), so they are not a participant.
      raise exception 'not allowed' using errcode = '42501';
    end if;
    if c.listing_status <> 'active' then
      raise exception 'listing is not available' using errcode = '23514';
    end if;
    if app.is_blocked_between(c.buyer_id, c.seller_id) then
      raise exception 'blocked' using errcode = '42501';
    end if;
    new.listing_id := c.listing_id;
    new.buyer_id := c.buyer_id;
    new.seller_id := c.seller_id;
    new.status := 'pending';
    new.created_at := now();
    new.expires_at := now() + interval '7 days';
    new.responded_at := null;
    return new;
  end if;

  -- End users may only change status. Internal updates (e.g. ON DELETE SET NULL
  -- when an account is deleted) must be allowed through.
  if not internal and (
     new.id <> old.id or new.conversation_id <> old.conversation_id
     or new.listing_id <> old.listing_id or new.amount_centavos <> old.amount_centavos
     or new.buyer_id is distinct from old.buyer_id
     or new.seller_id is distinct from old.seller_id
     or new.created_at <> old.created_at or new.expires_at <> old.expires_at) then
    raise exception 'offer field is read-only' using errcode = '42501';
  end if;

  if new.status <> old.status then
    if old.status <> 'pending' then
      raise exception 'offer was already answered' using errcode = '23514';
    end if;
    if internal then
      null;  -- system jobs (e.g. expiry) may move pending offers
    elsif new.status = 'withdrawn' and me = old.buyer_id then
      null;
    elsif new.status in ('accepted', 'rejected') and me = old.seller_id then
      if old.expires_at < now() then
        raise exception 'offer has expired' using errcode = '23514';
      end if;
    else
      raise exception 'not allowed to set offer to %', new.status using errcode = '42501';
    end if;
    new.responded_at := now();
  end if;
  return new;
end;
$$;
create trigger offers_guard before insert or update on app.offers
  for each row execute function app.offers_guard();

create function app.offers_announce() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into app.messages (conversation_id, sender_id, kind, body, offer_id)
    values (new.conversation_id, new.buyer_id, 'offer', 'Made an offer', new.id);
  elsif new.status <> old.status then
    insert into app.messages (conversation_id, sender_id, kind, body, offer_id)
    values (
      new.conversation_id,
      case when new.status = 'withdrawn' then new.buyer_id
           when new.status in ('accepted', 'rejected') then new.seller_id end,
      'system',
      case new.status
        when 'accepted' then 'Offer accepted'
        when 'rejected' then 'Offer declined'
        when 'withdrawn' then 'Offer withdrawn'
        else 'Offer expired' end,
      new.id
    );
  end if;
  return null;
end;
$$;
create trigger offers_announce after insert or update on app.offers
  for each row execute function app.offers_announce();

-- When a listing leaves 'active', pending offers expire.
create function app.listings_expire_offers() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if old.status = 'active' and new.status <> 'active' then
    update app.offers set status = 'expired'
     where listing_id = new.id and status = 'pending';
  end if;
  return null;
end;
$$;
create trigger listings_expire_offers after update of status on app.listings
  for each row execute function app.listings_expire_offers();

