-- True if either user blocked the other. Security definer because a user may
-- only read their own block list, but must not be able to message someone who
-- blocked them.
create function app.is_blocked_between(a uuid, b uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from app.blocked_users
    where (blocker_id = a and blocked_id = b) or (blocker_id = b and blocked_id = a)
  );
$$;

-- ---------------------------------------------------------------------------
-- Conversations
-- ---------------------------------------------------------------------------
create table app.conversations (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references app.listings (id) on delete cascade,
  buyer_id uuid references app.profiles (id) on delete set null,
  seller_id uuid references app.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  last_message_at timestamptz not null default now(),
  buyer_last_read_at timestamptz,
  seller_last_read_at timestamptz,
  constraint conversations_listing_buyer_uq unique (listing_id, buyer_id),
  constraint conversations_not_self check (buyer_id <> seller_id)
);
create index conversations_buyer_idx on app.conversations (buyer_id, last_message_at desc);
create index conversations_seller_idx on app.conversations (seller_id, last_message_at desc);

create function app.conversations_guard() returns trigger
-- Invoker rights on purpose: current_user tells end users apart from internal
-- triggers (which run as the table owner).
language plpgsql set search_path = '' as $$
declare
  l record;
begin
  if tg_op = 'INSERT' then
    select seller_id, status into l from app.listings where id = new.listing_id;
    if not found or l.status <> 'active' then
      raise exception 'listing is not available' using errcode = '23514';
    end if;
    new.seller_id := l.seller_id;  -- never trust a client-supplied seller
    if new.buyer_id = new.seller_id then
      raise exception 'cannot start a chat on your own listing' using errcode = '23514';
    end if;
    if app.is_blocked_between(new.buyer_id, new.seller_id) then
      raise exception 'blocked' using errcode = '42501';
    end if;
    new.created_at := now();
    new.last_message_at := now();
    new.buyer_last_read_at := null;
    new.seller_last_read_at := null;
    return new;
  end if;

  -- UPDATE by a participant: only their own read marker may move.
  if current_user in ('anon', 'authenticated') then
    if new.id <> old.id or new.listing_id <> old.listing_id
       or new.buyer_id is distinct from old.buyer_id
       or new.seller_id is distinct from old.seller_id
       or new.created_at <> old.created_at
       or new.last_message_at <> old.last_message_at then
      raise exception 'conversation field is read-only' using errcode = '42501';
    end if;
    if (select auth.uid()) is distinct from old.buyer_id
       and new.buyer_last_read_at is distinct from old.buyer_last_read_at then
      raise exception 'not your read marker' using errcode = '42501';
    end if;
    if (select auth.uid()) is distinct from old.seller_id
       and new.seller_last_read_at is distinct from old.seller_last_read_at then
      raise exception 'not your read marker' using errcode = '42501';
    end if;
  end if;
  return new;
end;
$$;
create trigger conversations_guard before insert or update on app.conversations
  for each row execute function app.conversations_guard();

